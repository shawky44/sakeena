'فَإِنَّ مَعَ الْعُسْرِ يُسْرًا ﴿٥ الشرح﴾',
'إِنَّ مَعَ الْعُسْرِ يُسْرًا ﴿٦ الشرح﴾',
'إِنَّا أَعْطَيْنَاكَ الْكَوْثَرَ ﴿١ الكوثر﴾',
'فَصَلِّ لِرَبِّكَ وَانْحَرْ ﴿٢ الكوثر﴾',
'إِنَّ شَانِئَكَ هُوَ الْأَبْتَرُ ﴿٣ الكوثر﴾',
'قُلْ هُوَ اللَّهُ أَحَدٌ ﴿١ الإخلاص﴾',
'اللَّهُ الصَّمَدُ ﴿٢ الإخلاص﴾',
'لَمْ يَلِدْ وَلَمْ يُولَدْ ﴿٣ الإخلاص﴾',
'وَلَمْ يَكُن لَّهُ كُفُوًا أَحَدٌ ﴿٤ الإخلاص﴾',
'إِنَّ اللّهَ مَعَ الصَّابِرِينَ ﴿١٥٣ البقرة﴾',
'وَبَشِّرِ الصَّابِرِينَ ﴿١٥٥ البقرة﴾',
'مَا يَلْفِظُ مِن قَوْلٍ إِلَّا لَدَيْهِ رَقِيبٌ عَتِيدٌ ﴿١٨ ق﴾',
