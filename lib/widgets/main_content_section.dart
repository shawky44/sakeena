  'تِلْكَ آيَاتُ الْكِتَابِ الْحَكِيمِ ﴿٢ لقمان﴾',
  'وَاذْكُرْنَ مَا يُتْلَىٰ فِي بُيُوتِكُنَّ مِنْ آيَاتِ اللَّهِ وَالْحِكْمَةِ ۚ إِنَّ اللَّهَ كَانَ لَطِيفًا خَبِيرًا ﴿٣٤ الأحزاب﴾',
  'وَمَا تَأْتِيهِم مِّنْ آيَةٍ مِّنْ آيَاتِ رَبِّهِمْ إِلَّا كَانُوا عَنْهَا مُعْرِضِينَ ﴿٤٦ يس﴾',
