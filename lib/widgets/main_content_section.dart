  Widget _buildPrayerTimeItem(String prayerName, String iconPath) {
    final isNextPrayer = prayerName == nextPrayerName;
    final time = allPrayerTimes[prayerName] ?? '--:--';

    return Expanded(
      child: Container(
        margin: const EdgeInsets.symmetric(horizontal: 1),
        padding: const EdgeInsets.symmetric(horizontal: 1, vertical: 9),
        decoration: BoxDecoration(
          color: isNextPrayer ? const Color(0xEB43635A) : Colors.transparent,
          borderRadius: BorderRadius.circular(10),
        ),
        child: LayoutBuilder(
          builder: (context, constraints) {
            final bool isSmall = constraints.maxWidth < 60;
            final double iconSize = isSmall ? 20 : 26;
            final double titleFontSize = isSmall ? 10 : 12;
            final double timeFontSize = isSmall ? 9 : 11;

            return Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                Image.asset(
                  iconPath,
                  width: iconSize,
                  height: iconSize,
                  color: Colors.black87,
                  errorBuilder: (context, error, stackTrace) {
                    return Icon(
                      Icons.mosque,
                      color: Colors.white,
                      size: iconSize + 2,
                    );
                  },
                ),
                const SizedBox(height: 3),
                Text(
                  prayerName,
                  style: TextStyle(
                    color: Colors.white,
                    fontSize: titleFontSize,
                    fontWeight: FontWeight.bold,
