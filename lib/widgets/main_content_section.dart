  // ==================== DATA HELPERS ====================
String _getDailyItem(List<String> items) {
  if (items.isEmpty) return '';
  final epoch = DateTime(2024, 1, 1);
  final daysSinceEpoch = DateTime.now().difference(epoch).inDays;
  final index = daysSinceEpoch % items.length;
  return items[index];
}

Map<String, String> _getDailyAllahName() {
  final epoch = DateTime(2024, 1, 1);
  final daysSinceEpoch = DateTime.now().difference(epoch).inDays;
  final index = daysSinceEpoch % allahNames.length;
  return allahNames[index];
}
